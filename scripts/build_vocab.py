def to_tw_business(text: str) -> str:
    if not text:
        return ""
    s = cc.convert(text)
    # 清除爬蟲雜訊段落與冷門無關 abbr.
    s = re.sub(r"[A-Za-z0-9]+abbr\..*$", "", s)
    s = re.sub(r"同類記憶法:.*$", "", s)
    s = re.sub(r"時態:.*$", "", s)
    s = re.sub(r"名\s*詞:.*$", "", s)
    s = re.sub(r"形容詞:.*$", "", s)
    s = re.sub(r"副\s*詞:.*$", "", s)
    s = re.sub(r"過去分詞:.*$", "", s)
    s = re.sub(r"現在分詞:.*$", "", s)
    s = re.sub(r"比較級:.*$", "", s)
    s = re.sub(r"最高級:.*$", "", s)
    s = re.sub(r"複\s*數:.*$", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    for src, dst in TW_TERM_FIXES:
        s = s.replace(src, dst)
    s = s.replace("； ;", "；").replace(" ; ", "；").strip(" ；;,")
    return s


